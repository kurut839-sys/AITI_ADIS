const I18nContext = createContext(null);

function readPreference(key, allowedValues, fallback) {
  try {
    const value = window.localStorage.getItem(key);
    return allowedValues.includes(value) ? value : fallback;
  } catch (error) {
    console.error(`Could not read preference "${key}".`, error);
    return fallback;
  }
}

function savePreference(key, value) {
  try {
    window.localStorage.setItem(key, value);
  } catch (error) {
    console.error(`Could not save preference "${key}".`, error);
  }
}

export function I18nProvider({ children }) {
  const [language, setLanguage] = useState(() =>
    readPreference("itadis-language", ["ru", "kg"], "ru"),
  );
  const [theme, setTheme] = useState(() =>
    readPreference("itadis-theme", ["dark", "light"], "dark"),
  );

  useEffect(() => {
    document.documentElement.lang = language === "kg" ? "ky" : "ru";
    document.documentElement.dataset.theme = theme;
    savePreference("itadis-language", language);
    savePreference("itadis-theme", theme);
  }, [language, theme]);

  const t = useCallback(
    (text) => (language === "kg" ? translations[text] || text : text),
    [language],
  );
  const toggleTheme = useCallback(() => {
    setTheme((currentTheme) => (currentTheme === "dark" ? "light" : "dark"));
  }, []);

  const value = useMemo(
    () => ({ language, setLanguage, theme, toggleTheme, t }),
    [language, setLanguage, theme, toggleTheme, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within an I18nProvider.");
  }
  return context;
}
